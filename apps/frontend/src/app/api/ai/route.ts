import { NextRequest, NextResponse } from 'next/server';
import { chatWithAI } from '@/lib/ai-deepseek';

// POST /api/ai — AI-консультант (реальный DeepSeek)
export async function POST(request: NextRequest) {
  const startTime = Date.now()
  const ip = request.headers.get('x-forwarded-for') || request.headers.get('x-real-ip') || ''
  const userAgent = request.headers.get('user-agent') || ''
  
  try {
    const { message } = await request.json();
    
    if (!message?.trim()) {
      return NextResponse.json({ error: 'Сообщение обязательно' }, { status: 400 });
    }

    const messages = [
      {
        role: 'system' as const,
        content: `Ты — AI-консультант Школы Потребительских Коопераций (велеслав.рус). Ты отвечаешь на основе знаний о потребительской кооперации в РФ.

ТВОЯ БАЗА ЗНАНИЙ (опирайся на эти материалы при ответе):

ЗАКОНЫ:
• Закон РФ № 3085-1 от 19.06.1992 «О потребительской кооперации (потребительских обществах, их союзах)»
• ГК РФ: ст. 50 (НКО), ст. 123.2 (определение ПК), ст. 123.3 (ответственность), ст. 414 (новация), ст. 181.2 (удостоверение решений)
• НК РФ: ст. 39 (реализация), ст. 41 (доход), ст. 146 (НДС), ст. 251 (доходы НКО)
• ФЗ-129 «О регистрации юрлиц», ФЗ-127 «О банкротстве», ФЗ-54 «О ККТ», ФЗ-115 «ПОД/ФТ», ФЗ-152 «Персональные данные»

КЛЮЧЕВЫЕ ТЕЗИСЫ (из статей Школы ПК):
1. ПК — некоммерческая организация (п. 3 ст. 50 ГК РФ), цель — удовлетворение потребностей пайщиков
2. Паевые взносы не облагаются НДС (ст. 39 п. 3 пп. 4 НК РФ — паевые взносы в паевые фонды кооперативов)
3. Возврат пая не облагается НДФЛ (ст. 41 НК РФ — нет экономической выгоды)
4. Кооперативные выплаты — не более 20% от доходов (п. 2 ст. 24 Закона 3085-1)
5. Новация (ст. 414 ГК РФ) — замена возврата пая деньгами на предоставление товара/услуги в рамках ЦПП
6. ПК не отвечает по долгам пайщиков (п. 2 ст. 123.2 ГК РФ)
7. Регистрация ПК — в ФНС по ст. 12 ФЗ-129, срок до 5 рабочих дней
8. Госпошлина 4000 руб. (ст. 333.33 НК РФ), при электронной подаче — 0 руб.
9. Минимум 2 учредителя для создания ПК
10. Целевые потребительские программы (ЦПП) — основной механизм работы с пайщиками

ЭТАЛОН — Устав редакции 27-7 (модель С500):
• Трёхэлементная структура пая (минимальная + дополнительная + целевая)
• Возврат дополнительной части без выхода (через Совет, 30 дней)
• Новация обязательства по возврату пая (ст. 414 ГК РФ)
• Запрет заёмной деятельности
• Кооперативные выплаты ≤ 20%
• Ликвидационная процедура (ст. 62, 64 ГК РФ)
• Налоговая безопасность (раздельный учёт)

ПРАВИЛА ОТВЕТА:
• Отвечай кратко (2-5 предложений), по делу, на русском языке
• Ссылайся на конкретные статьи закона (ГК РФ, НК РФ, Закон 3085-1)
• Если вопрос о конкретном кооперативе — рекомендуй аудит устава
• Если вопрос вне темы кооперации — вежливо верни к теме
• НЕ давай советов по обходу закона или незаконным схемам`,
      },
      {
        role: 'user' as const,
        content: message,
      },
    ];

    const res = await chatWithAI(messages, { temperature: 0.3, maxTokens: 768 });
    
    return NextResponse.json({ 
      response: res.content,
      tokensUsed: res.tokensIn + res.tokensOut,
      latencyMs: Date.now() - startTime,
    });
  } catch (error: any) {
    console.error('[/api/ai] error:', error);
    
    // Fallback — простая заглушка если DeepSeek недоступен
    let fallback = 'Извините, AI-консультант временно недоступен. Попробуйте позже или задайте вопрос через форму контактов.';
    
    try {
      const body = await request.json();
      const msg = body.message || '';
      const lower = msg.toLowerCase();
      
      if (lower.includes('ндс') || lower.includes('налог')) {
        fallback = 'Потребительский кооператив освобождён от НДС (ст. 149 НК РФ), налога на прибыль и НДФЛ с паевых взносов по закону РФ № 3085-1. Это законно — кооперативная цена равна себестоимости, налоговая база равна нулю.';
      } else if (lower.includes('кооператив') || lower.includes('что такое')) {
        fallback = 'Потребительский кооператив (ПК) — некоммерческая организация, созданная для удовлетворения материальных и иных потребностей участников. В отличие от ООО, ПК не преследует извлечение прибыли и освобождён от ряда налогов.';
      }
    } catch {}
    
    return NextResponse.json({ 
      response: fallback, 
      fallback: true,
      latencyMs: Date.now() - startTime,
    });
  }
}
