/**
 * Формирует пользовательское сообщение для LLM с текстом устава.
 * Передаётся как role: 'user'.
 *
 * @param documentText — извлечённый из файла текст устава
 * @param fileName — оригинальное имя файла (для контекста)
 */
export function buildUserMessage(documentText: string, fileName?: string): string {
  const trimmed = documentText.trim()
  const header = fileName
    ? `Проанализируй устав потребительского кооператива из файла «${fileName}».`
    : 'Проанализируй представленный ниже устав потребительского кооператива.'

  return `${header}

Ниже — текст устава (извлечён из загруженного документа).

--- НАЧАЛО ТЕКСТА УСТАВА ---
${trimmed}
--- КОНЕЦ ТЕКСТА УСТАВА ---

Верни результат СТРОГО в формате JSON согласно инструкции. Не добавляй текст вне JSON.`
}


